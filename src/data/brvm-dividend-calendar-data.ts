// Helper: Get peak dividend season stats
export function getDividendCalendarStats(dividends: BRVMCalendarDividend[]) {
  const totalCount = dividends.length;
  const confirmedCount = dividends.filter(d => d.payoutStatus === 'CONFIRMED').length;
  const announcedCount = dividends.filter(d => d.payoutStatus === 'ANNOUNCED').length;
  const estimatedCount = dividends.filter(d => d.payoutStatus === 'ESTIMATED').length;

  const totalGrossDistributionFcfa = dividends.reduce((sum, d) => sum + d.grossDividend, 0);
  const averageGrossDividend = totalCount > 0 ? Math.round(totalGrossDistributionFcfa / totalCount) : 0;

  // Monthly distributions count
  const monthlyBreakdown: Record<number, { count: number; totalGross: number; companies: string[] }> = {};
  for (let m = 1; m <= 12; m++) {
    monthlyBreakdown[m] = { count: 0, totalGross: 0, companies: [] };
  }

  dividends.forEach(d => {
    if (d.paymentDate) {
      const month = new Date(d.paymentDate).getMonth() + 1; // 1 to 12
      if (monthlyBreakdown[month]) {
        monthlyBreakdown[month].count += 1;
        monthlyBreakdown[month].totalGross += d.grossDividend;
        monthlyBreakdown[month].companies.push(d.companySymbol);
      }
    }
  });

  return {
    totalCount,
    confirmedCount,
    announcedCount,
    estimatedCount,
    totalGrossDistributionFcfa,
    averageGrossDividend,
    monthlyBreakdown,
  };
}

// Helper: Generate .ics iCalendar file content for any dividend or list of dividends
export function generateDividendICS(dividends: BRVMCalendarDividend[]): string {
  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//BourseFacile//BRVM Dividend Calendar//FR',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'X-WR-CALNAME:Dividendes BRVM',
    'X-WR-TIMEZONE:Africa/Abidjan',
  ];

  dividends.forEach(d => {
    if (!d.paymentDate) return;
    const dateObj = new Date(d.paymentDate);
    const dateStr = dateObj.toISOString().split('T')[0].replace(/-/g, '');
    const exDateStr = d.exDate ? new Date(d.exDate).toLocaleDateString('fr-FR') : 'Non communiquée';

    lines.push('BEGIN:VEVENT');
    lines.push(`UID:brvm-div-${d.companySymbol}-${d.year}@boursefacile.app`);
    lines.push(`DTSTAMP:${dateStr}T090000Z`);
    lines.push(`DTSTART;VALUE=DATE:${dateStr}`);
    lines.push(`DTEND;VALUE=DATE:${dateStr}`);
    lines.push(`SUMMARY:💰 Dividende BRVM: ${d.companySymbol} (${d.companyName}) - ${d.netDividend} FCFA Net`);
    lines.push(
      `DESCRIPTION:Paiement officiel du dividende ${d.companyName} (${d.companySymbol})\\n` +
      `Montant brut: ${d.grossDividend} FCFA\\n` +
      `Montant net après IRVM 10%: ${d.netDividend} FCFA\\n` +
      `Date de détachement: ${exDateStr}\\n` +
      `SGI Centralisatrice: ${d.payingAgent}\\n` +
      `Réf: ${d.officialNoticeRef || 'Avis BRVM'}\\n` +
      `${d.commentary.replace(/\n/g, ' ')}`
    );
    lines.push(`LOCATION:Bourse Régionale des Valeurs Mobilières (BRVM), Abidjan`);
    lines.push('STATUS:CONFIRMED');
    lines.push('END:VEVENT');
  });

  lines.push('END:VCALENDAR');
  return lines.join('\r\n');
}
